"""docs/watch-report.md from the watch's candidates (tools/watch/run.py calls render())."""
import collections
import datetime

ORDER = ["in a list, not yet in GridFit", "new to GridFit", "family known, in no list yet", "close to a listed model",
         "in GridFit", "no model code"]
CAP = 40


def _cell(s):
    return str(s or "").replace("|", "/").replace("\n", " ")[:90]


def _lead(codes):
    days = []
    for rec in codes.values():
        if rec.get("listed") and not rec.get("baseline"):
            d = (datetime.date.fromisoformat(rec["listed"]) - datetime.date.fromisoformat(rec["first_seen"])).days
            days.append(d)
    return days


def render(run, edge, state, edge_state, codes):
    cands = list(run.get("candidates", []))
    if edge.get("candidates"):
        cands += [dict(c, source=c["source"] + " (Edge, " + edge.get("run", "") + ")") for c in edge["candidates"]]
    L = [f"# Watch report — {run['run']}", "",
         "Generated by `python tools/watch/run.py` (docs/freshness.md explains the sources and the rhythm). "
         "Never edit by hand.", "",
         f"Register snapshot compared with: **{run.get('snapshot') or 'none'}**. HTTP requests this run: {run.get('requests', 0)}.", ""]

    # --- the summary Madis reads first
    fresh = [c for c in cands if not c.get("baseline")]
    by = collections.Counter(c["verdict"] for c in fresh if c.get("norm"))
    base = collections.Counter(c["verdict"] for c in cands if c.get("baseline") and c.get("norm"))
    L += ["## Summary", "", "Rows per verdict; one code can come from several sources, so the last line counts codes once.", "",
          "| verdict | new this run | first run of a source (baseline) |", "|---|---:|---:|"]
    for v in ORDER[:-1]:
        L.append(f"| {v} | {by.get(v, 0)} | {base.get(v, 0)} |")
    L += [f"| distinct model codes | {len({c['norm'] for c in fresh if c.get('norm')})} | "
          f"{len({c['norm'] for c in cands if c.get('baseline') and c.get('norm')})} |", ""]
    lead = _lead(codes)
    if lead:
        lead.sort()
        L += [f"Lead time so far: {len(lead)} codes were seen on a maker's site, in the press or in an integration "
              f"before a list carried them; median {lead[len(lead) // 2]} days, longest {lead[-1]} days.", ""]
    else:
        L += ["Lead time: not measured yet. It counts codes first seen after the baseline that a list later carries.", ""]

    # --- registers
    pend = run.get("registers_pending") or {}
    L += ["## Grid lists since the last register refresh", ""]
    if pend.get("lists") is not None:
        lists = pend.get("lists") or {}
        if lists:
            L += ["| list | list date then → now | rows added | removed | changed |", "|---|---|---:|---:|---:|"]
            for reg, r in sorted(lists.items()):
                L.append(f"| {reg} | {r['previous_source_date'] or '—'} → {r['source_date'] or '—'} | {len(r['added'])} | "
                         f"{len(r['removed'])} | {len(r['changed'])} |")
            L += ["", "A list that moved means the next `python build.py --registers-refresh` brings these rows into "
                      "GridFit (by hand, or the `refresh` workflow's registers input)."]
        else:
            L.append(f"No list read by the watch has changed since the snapshot of {pend.get('snapshot')}.")
        for reg, why in sorted((pend.get("skipped") or {}).items()):
            L.append(f"- **{reg} not read by the watch:** {why}.")
        L.append("")
    else:
        L += ["Not run this time.", ""]

    # --- candidates by verdict
    for v in ORDER:
        rows = [c for c in cands if c["verdict"] == v and (v != "in GridFit" or not c.get("baseline"))]
        if v == "no model code":
            rows = [c for c in rows if not c.get("baseline")]
        if not rows:
            continue
        L += [f"## {v[0].upper() + v[1:]} ({len(rows)})", ""]
        if v == "in GridFit":
            L.append("Codes a source just mentioned that GridFit already shows. Listed for completeness.")
            L.append("")
        L += ["| source | brand | code / title | lists | family | seen |", "|---|---|---|---|---|---|"]
        rows.sort(key=lambda c: (bool(c.get("baseline")), c["source"], c.get("brand") or "", c.get("code") or c["title"]))
        for c in rows[:CAP]:
            what = c.get("code") or c["title"]
            link = f"[{_cell(what)}]({c['url']})" if c.get("url") else _cell(what)
            lists = ", ".join(c.get("in_lists") or []) or (c.get("list", "") + (" " + c.get("status_word", "")).rstrip())
            if c.get("partial"):
                lists = "close: " + ", ".join(c["partial"][:2])
            seen = "baseline" if c.get("baseline") else _cell(c.get("date"))[:16]
            L.append(f"| {c['source']} | {_cell(c.get('brand'))} | {link} | {_cell(lists)} | {_cell(c.get('family'))} | {seen} |")
        if len(rows) > CAP:
            L.append(f"| … | | {len(rows) - CAP} more in `data/watch/candidates.json` | | | |")
        L.append("")

    # --- sources
    L += ["## Sources this run", "", "| source | kind | status | items | new | note |", "|---|---|---|---:|---:|---|"]
    for sid, st in sorted({**state, **{k + " (Edge)": v for k, v in edge_state.items()}}.items()):
        L.append(f"| {sid} | {st.get('kind', '')} | {st.get('status', '')} | {st.get('items', '')} | {st.get('new', '')} | "
                 f"{_cell(st.get('error'))} |")
    if run.get("log"):
        L += ["", "Log:", ""] + [f"- {_cell(x)}" for x in run["log"]]
    return "\n".join(L) + "\n"
